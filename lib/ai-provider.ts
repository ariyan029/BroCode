/**
 * Generate code suggestions with automatic Ollama -> Cloud fallback
 */
export async function generateCodeSuggestionAI(prompt: string): Promise<AIResponse> {
  // 1. Try Local Ollama first
  try {
    const text = await callOllama(prompt, 2500);
    if (text) {
      return { text: cleanCodeResponse(text), model: OLLAMA_MODEL, provider: "ollama" };
    }
  } catch {
    console.warn("Local Ollama not reachable, checking cloud fallbacks...");
  }

  // 2. Try Gemini API fallback
  if (process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY) {
    try {
      const text = await callGemini(prompt);
      return {
        text: cleanCodeResponse(text),
        model: process.env.GEMINI_MODEL || "gemini-2.0-flash",
        provider: "gemini",
      };
    } catch (err) {
      console.error("Gemini API suggestion error:", err);
    }
  }

  // 3. Try Groq API fallback
  if (process.env.GROQ_API_KEY) {
    try {
      const text = await callGroq([
        { role: "system", content: "You are an expert code completion engine. Return only the code to insert at cursor." },
        { role: "user", content: prompt },
      ]);
      return {
        text: cleanCodeResponse(text),
        model: process.env.GROQ_MODEL || "llama-3.3-70b-versatile",
        provider: "groq",
      };
    } catch (err) {
      console.error("Groq suggestion error:", err);
    }
  }

  // 4. Try OpenAI fallback
  if (process.env.OPENAI_API_KEY) {
    try {
      const text = await callOpenAI([
        { role: "system", content: "You are an expert code completion engine. Return only the code to insert at cursor." },
        { role: "user", content: prompt },
      ]);
      return {
        text: cleanCodeResponse(text),
        model: process.env.OPENAI_MODEL || "gpt-4o-mini",
        provider: "openai",
      };
    } catch (err) {
      console.error("OpenAI suggestion error:", err);
    }
  }

  // 5. Friendly informative message if neither is configured
  return {
    text: "// AI offline: Run 'ollama run codellama' locally or add GEMINI_API_KEY in .env.local for cloud inference.",
    model: "offline",
    provider: "fallback",
  };
}

/**
 * Generate chat assistant answers with automatic Ollama -> Cloud fallback
 */
export async function generateChatResponseAI(
  messages: ChatMessage[],
  systemPrompt: string
): Promise<AIResponse> {
  const fullPrompt = [
    `System: ${systemPrompt}`,
    ...messages.map((m) => `${m.role === "assistant" ? "Assistant" : "User"}: ${m.content}`),
  ].join("\n\n");

  // 1. Try Local Ollama first
  try {
    const text = await callOllama(fullPrompt, 2500);
    if (text) {
      return { text: text.trim(), model: OLLAMA_MODEL, provider: "ollama" };
    }
  } catch {
    console.warn("Local Ollama not reachable for chat, checking cloud fallbacks...");
  }

  // 2. Try Gemini API fallback
  if (process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY) {
    try {
      const lastUserMsg = messages[messages.length - 1]?.content || "";
      const history = messages.slice(0, -1);
      const text = await callGemini(lastUserMsg, systemPrompt, history);
      return {
        text: text.trim(),
        model: process.env.GEMINI_MODEL || "gemini-2.0-flash",
        provider: "gemini",
      };
    } catch (err) {
      console.error("Gemini chat error:", err);
    }
  }

  // 3. Try Groq fallback
  if (process.env.GROQ_API_KEY) {
    try {
      const text = await callGroq([{ role: "system", content: systemPrompt }, ...messages]);
      return {
        text: text.trim(),
        model: process.env.GROQ_MODEL || "llama-3.3-70b-versatile",
        provider: "groq",
      };
    } catch (err) {
      console.error("Groq chat error:", err);
    }
  }

  // 4. Try OpenAI fallback
  if (process.env.OPENAI_API_KEY) {
    try {
      const text = await callOpenAI([{ role: "system", content: systemPrompt }, ...messages]);
      return {
        text: text.trim(),
        model: process.env.OPENAI_MODEL || "gpt-4o-mini",
        provider: "openai",
      };
    } catch (err) {
      console.error("OpenAI chat error:", err);
    }
  }

  // 5. Friendly informative response
  return {
    text: "Hello! The AI service is currently in offline mode.\n\nTo enable AI responses:\n1. **For Local Use:** Install [Ollama](https://ollama.com/) and run `ollama run codellama` in your terminal.\n2. **For Cloud / Vercel:** Add `GEMINI_API_KEY=your_key` or `GROQ_API_KEY=your_key` to your `.env.local` file.",
    model: "system-guidance",
    provider: "fallback",
  };
}

function cleanCodeResponse(suggestion: string): string {
  let cleaned = suggestion;
  if (cleaned.includes("```")) {
    const codeMatch = cleaned.match(/```[\w]*\n?([\s\S]*?)```/);
    cleaned = codeMatch ? codeMatch[1].trim() : cleaned;
  }
  return cleaned.trim();
}
